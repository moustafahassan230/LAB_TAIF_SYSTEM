-- LAB TAIF: Audit Log table
-- Run this once in Supabase SQL Editor.
create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_name text,
  user_username text,
  action text not null,
  details text
);

create index if not exists audit_log_created_at_idx
  on public.audit_log (created_at desc);

create index if not exists audit_log_action_idx
  on public.audit_log (action);

alter table public.audit_log enable row level security;

-- This app currently uses the Supabase client directly.
-- If your project has RLS enabled, allow the app's current access model:
drop policy if exists "LAB TAIF audit read" on public.audit_log;
drop policy if exists "LAB TAIF audit insert" on public.audit_log;

create policy "LAB TAIF audit read"
on public.audit_log for select
using (true);

create policy "LAB TAIF audit insert"
on public.audit_log for insert
with check (true);
